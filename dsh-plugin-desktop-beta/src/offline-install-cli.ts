/**
 * Install offline CLIs and expose them on the user's PATH.
 *
 * The commands land in `~/.dsh/bin`, the conventional place for DSH's own command line
 * tools. Nothing else in the product writes there, so a shim the installer creates
 * survives a relaunch — unlike the per-session terminal shims, which live in the
 * terminal's own state directory.
 *
 * Shims are generated as shell scripts that `exec` the installed binary, so a command
 * costs one process, not two.
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { randomUUID } from 'node:crypto'
import {
  offlineTarballExists,
  offlineTarballPath,
  readOfflineTarball,
  type OfflineCliEntry,
  type OfflineInstallManifest,
} from './offline-install-manifest.ts'
import { DIRECTORY_MODE, STAMP_MODE, VERSION_STAMP, installedVersion } from './offline-install-store.ts'
import { unpackTree } from './offline-install-unpack.ts'

/** Mode of a generated shim. */
const EXECUTABLE_MODE = 0o755

/** Banner every generated shim carries, so a reader knows it is not hand-written. */
export const SHIM_BANNER = 'Generated by the DSH Desktop client. Do not edit: it is rewritten on launch.'

/**
 * Quote one shell argument.
 *
 * Single quotes make every byte literal except `'` itself, which is closed, escaped and
 * reopened — the only form that survives spaces, `$`, backticks and newlines alike.
 */
export function quoteShell(value: string): string {
  return `'${value.replaceAll("'", `'"'"'`)}'`
}

/** Build the shim that runs one installed command. */
export function cliShim(executablePath: string): string {
  return [
    '#!/bin/sh',
    `# ${SHIM_BANNER}`,
    `exec ${quoteShell(executablePath)} "$@"`,
    '',
  ].join('\n')
}

/** Build the Windows shim that runs the same executable. */
export function cliShimWindows(executablePath: string): string {
  return [
    '@echo off',
    `rem ${SHIM_BANNER}`,
    `"${executablePath}" %*`,
    'exit /b %errorlevel%',
    '',
  ].join('\r\n')
}

/** Write a file atomically, so a reader never sees a half-written shim. */
function writeAtomic(filename: string, contents: string, mode: number): void {
  mkdirSync(dirname(filename), { recursive: true, mode: DIRECTORY_MODE })
  const temporary = join(dirname(filename), `.${basename(filename)}.${process.pid}.${randomUUID()}.tmp`)
  try {
    writeFileSync(temporary, contents, { encoding: 'utf8', flag: 'wx', mode })
    chmodSync(temporary, mode)
    renameSync(temporary, filename)
  } finally {
    rmSync(temporary, { force: true })
  }
}

/** One CLI that was installed, or why it was not. */
export interface CliOutcome {
  /** Command name from the manifest. */
  readonly name: string
  /** What happened. `current` means it was already at the manifest version. */
  readonly action: 'installed' | 'current' | 'failed'
  /** Where the command landed, when one was written. */
  readonly shimPath?: string
  /** Why it failed, when it did. */
  readonly reason?: string
}

/** Where offline CLIs and their commands live. */
export interface CliInstallLocation {
  /** Root holding one unpacked directory per CLI, e.g. `~/.dsh/offline/cli`. */
  readonly installRoot: string
  /** Directory receiving the generated commands, e.g. `~/.dsh/bin`. */
  readonly shimRoot: string
  /** Host platform; `win32` gets batch shims. */
  readonly platform: string
}

/** Write the command files that expose one installed CLI. */
function writeShims(
  executable: string,
  shimPath: string,
  windowsShimPath: string,
  platform: string,
): void {
  // A `.cmd` beside the POSIX shim lets a Windows shell find the same command, and on
  // Windows it is the only usable form.
  writeAtomic(windowsShimPath, cliShimWindows(executable), EXECUTABLE_MODE)
  if (platform === 'win32') return
  writeAtomic(shimPath, cliShim(executable), EXECUTABLE_MODE)
}

/**
 * Unpack a CLI tarball and expose its command.
 *
 * The archive is unpacked with its single top-level directory stripped: a CLI tarball
 * is a tool tree, not an npm package, so `bin/codegraph` must end up directly under the
 * install root rather than nested inside a versioned folder.
 *
 * @param archive - Compressed tarball bytes read from the payload.
 * @param entry - CLI declaration from the manifest.
 * @param location - Where to unpack and where to write the command.
 * @returns What happened, including why it failed.
 */
export function installCli(archive: Buffer, entry: OfflineCliEntry, location: CliInstallLocation): CliOutcome {
  const root = join(location.installRoot, entry.name)
  const shimPath = join(location.shimRoot, entry.name)
  const windowsShimPath = join(location.shimRoot, `${entry.name}.cmd`)
  try {
    const alreadyCurrent = installedVersion(root) === entry.version
    unpackTree(archive, root, true)

    const executable = join(root, entry.executable)
    if (!existsSync(executable)) {
      // A CLI without its command is not an install; leaving it would make the next run
      // believe the version was satisfied.
      rmSync(root, { recursive: true, force: true })
      return { name: entry.name, action: 'failed', reason: `the archive contains no ${entry.executable}` }
    }

    chmodSync(executable, EXECUTABLE_MODE)
    writeAtomic(join(root, VERSION_STAMP), `${entry.version}\n`, STAMP_MODE)
    writeShims(executable, shimPath, windowsShimPath, location.platform)
    return { name: entry.name, action: alreadyCurrent ? 'current' : 'installed', shimPath }
  } catch (cause) {
    return {
      name: entry.name,
      action: 'failed',
      reason: cause instanceof Error ? cause.message : String(cause),
    }
  }
}

/**
 * Install every CLI the manifest declares.
 *
 * One CLI failing never stops the others or the caller: a broken tarball should cost
 * its own command, not the whole preinstall.
 *
 * @param manifest - Validated manifest.
 * @param location - Where to unpack and where to write commands.
 * @returns One outcome per declared CLI, in manifest order.
 */
export function installManifestClis(
  manifest: OfflineInstallManifest,
  location: CliInstallLocation,
): CliOutcome[] {
  return manifest.clis.map(entry => {
    const tarball = offlineTarballPath(manifest, entry.tarball)
    if (!offlineTarballExists(manifest, entry.tarball)) {
      return { name: entry.name, action: 'failed' as const, reason: `tarball is missing: ${tarball}` }
    }
    let archive: Buffer
    try {
      archive = readOfflineTarball(manifest, entry.tarball)
    } catch (cause) {
      return {
        name: entry.name,
        action: 'failed' as const,
        reason: `cannot read ${tarball}: ${cause instanceof Error ? cause.message : String(cause)}`,
      }
    }
    return installCli(archive, entry, location)
  })
}

/**
 * Ensure `~/.dsh/bin` is on the user's PATH by appending an idempotent block.
 *
 * Only files that already exist are touched: creating a shell profile the user never
 * had would be a surprise, and an uninstall could not safely remove it.
 *
 * @param shimRoot - Directory to add, e.g. `~/.dsh/bin`.
 * @param homeDir - Home directory holding the shell profiles.
 * @param platform - Host platform; Windows relies on the user's own PATH.
 * @returns The profiles that were changed.
 */
export function ensureShimDirectoryOnPath(shimRoot: string, homeDir: string, platform: string): string[] {
  if (platform === 'win32') return []
  const begin = '# >>> dsh offline cli >>>'
  const end = '# <<< dsh offline cli <<<'
  const block = [
    begin,
    `# Added by DSH Desktop so the bundled offline commands are on PATH.`,
    `export PATH=${quoteShell(shimRoot)}:"$PATH"`,
    end,
    '',
  ].join('\n')

  const changed: string[] = []
  for (const name of ['.zshrc', '.bashrc', '.bash_profile', '.profile']) {
    const profile = join(homeDir, name)
    if (!existsSync(profile)) continue
    let existing: string
    try {
      existing = readFileSync(profile, 'utf8')
    } catch {
      continue
    }
    const from = existing.indexOf(begin)
    if (from !== -1) {
      const to = existing.indexOf(end)
      const current = to === -1 ? undefined : existing.slice(from, to + end.length + 1)
      if (current === block) continue
      const next = to === -1
        ? `${existing.trimEnd()}\n${block}`
        : `${existing.slice(0, from)}${block}${existing.slice(to + end.length + 1)}`
      writeAtomic(profile, next, 0o644)
      changed.push(profile)
      continue
    }
    writeAtomic(profile, `${existing.trimEnd()}\n${block}`, 0o644)
    changed.push(profile)
  }
  return changed
}
